    private void jButton1DeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1DeleteActionPerformed
        // TODO add your handling code here:

    DefaultTableModel orderModel =
            (DefaultTableModel) jTable1.getModel();

    int selectedRow = jTable1.getSelectedRow();

    if (selectedRow != -1) {

        // Remove selected row from JTable
        orderModel.removeRow(selectedRow);

        // Remove the saved record
        appController.deleteOrderRecord(selectedRow);

        JOptionPane.showMessageDialog(
                this,
                "Selected order item removed.",
                "Success",
                JOptionPane.INFORMATION_MESSAGE
        );

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Please select an order to delete.",
                "Warning",
                JOptionPane.WARNING_MESSAGE
        );
    }

    }//GEN-LAST:event_jButton1DeleteActionPerformed
 

