    private void loadSavedOrders() {

    DefaultTableModel orderModel =
            (DefaultTableModel) jTable1.getModel();

    orderModel.setRowCount(0);

    for (Object[] record : appController.getOrderRecords()) {
        orderModel.addRow(record);
    }

    // Restore Best Seller table
    DefaultTableModel bestSellerModel =
            (DefaultTableModel) jTable2BestSellet.getModel();

    appController.updateBestSellerTable(bestSellerModel);
}

     private void setupTableColorRenderer() {
        jTable1.setDefaultRenderer(Object.class, new javax.swing.table.DefaultTableCellRenderer() {
            @Override
            public java.awt.Component getTableCellRendererComponent(javax.swing.JTable table, Object value, 
                    boolean isSelected, boolean hasFocus, int row, int column) {
                
                java.awt.Component c = super.getTableCellRendererComponent(table, value, isSelected, hasFocus, row, column);
                
                // Get status value from the last column (Column index 5 is "Status")
                Object statusObj = table.getModel().getValueAt(row, 5);
                String status = (statusObj != null) ? statusObj.toString() : "";
                
                if (!isSelected) {
                    if (status.equalsIgnoreCase("Paid")) {
                        c.setBackground(new java.awt.Color(200, 255, 200)); // Light Green for Paid
                        c.setForeground(new java.awt.Color(0, 100, 0));       // Dark Green text
                    } else {
                        c.setBackground(new java.awt.Color(255, 220, 220)); // Light Red/Pink for Pending/Unpaid
                        c.setForeground(new java.awt.Color(150, 0, 0));       // Dark Red text
                    }
                } else {
                    // Keep default selection colors if the row is clicked/selected
                    c.setBackground(table.getSelectionBackground());
                    c.setForeground(table.getSelectionForeground());
                }
                
                return c;
            }
        });
    }
  
